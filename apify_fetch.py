#!/usr/bin/env python3
"""apify_fetch.py - run the Apify actors in actor-inputs.json and save raw datasets.

Built so an agent without big-tool-result overflow (Codex CLI) can feed
jobpipe.py without pasting JSON through the conversation. Stdlib only.

  export APIFY_TOKEN=...
  python3 apify_fetch.py scrape  --outdir runs/2026-10-13
      -> runs/<date>/linkedin.json, naukri.json, indeed.json (both Indeed passes merged)
  python3 apify_fetch.py details --triage runs/<date>/triage.json --out runs/<date>/details.json
      -> {job_id: description} for triage_priority == "primary".
         LinkedIn/Indeed descriptions are already in pass 1 (free);
         only Naukri primaries with no description trigger naukri pass 2.
  python3 apify_fetch.py dataset <datasetId> --out file.json
      -> download an existing dataset (e.g. a run started from the Apify MCP).

Never edits jobpipe.py, config.json, seen-jobs.json or applied-companies.json.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

import jsprofile

HERE = os.path.dirname(os.path.abspath(__file__))
API = "https://api.apify.com/v2"

# config key -> actor. Keys without an "_actor" field inherit from their pass-1 sibling.
ACTOR_FOR = {
    "linkedin": "cheap_scraper/linkedin-job-scraper",
    "naukri_pass1": "blackfalcondata/naukri-jobs-feed",
    "naukri_pass2_template": "blackfalcondata/naukri-jobs-feed",
    "indeed": "kaix/indeed-scraper",
    "indeed_remote_pass": "kaix/indeed-scraper",
}


def _token() -> str:
    jsprofile.load_env()
    t = os.environ.get("APIFY_TOKEN")
    if not t or "PASTE" in t:
        sys.exit("APIFY_TOKEN is not set. Put APIFY_TOKEN=... in .env (see README).")
    return t


def _req(method: str, path: str, body: dict | None = None, query: dict | None = None,
         timeout: int = 90):
    url = f"{API}{path}"
    if query:
        url += "?" + urllib.parse.urlencode(query)
    data = json.dumps(body).encode() if body is not None else None
    r = urllib.request.Request(url, data=data, method=method, headers={
        "Authorization": f"Bearer {_token()}", "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(r, timeout=timeout) as resp:
            return json.loads(resp.read().decode() or "null")
    except urllib.error.HTTPError as e:
        sys.exit(f"Apify {method} {path} -> HTTP {e.code}: {e.read().decode()[:500]}")
    except urllib.error.URLError as e:
        sys.exit(f"Cannot reach api.apify.com ({e.reason}). Check the internet "
                 "connection, then retry. Do not fall back to an Apify MCP server.")


def cmd_whoami(a=None) -> int:
    """Print which Apify account APIFY_TOKEN belongs to (never the token)."""
    me = (_req("GET", "/users/me") or {}).get("data") or {}
    print(f"apify account: {me.get('username')} (id {me.get('id')})")
    expected = os.environ.get("APIFY_EXPECTED_USER", "").strip()
    if not expected or expected.startswith("your-"):
        print("WARN APIFY_EXPECTED_USER is not set in .env: account not cross-checked")
        expected = ""
    if expected and expected != me.get("username"):
        print(f"ERROR: expected Apify user '{expected}'. Wrong token: stop.")
        return 2
    return 0


def load_inputs() -> dict:
    """The active profile's actor-inputs.json (generated by `jptools.py build-inputs`)."""
    p = jsprofile.profile_dir() / "actor-inputs.json"
    if not p.exists():
        sys.exit(f"{p} is missing. Run: python3 jptools.py build-inputs")
    with open(p) as fh:
        return json.load(fh)


def clean_input(cfg: dict) -> dict:
    """Strip the _note/_actor/_changed annotation keys before sending to the actor."""
    return {k: v for k, v in cfg.items() if not k.startswith("_")}


def search_inputs(cfg: dict):
    """Expand local single-keyword searches without leaking metadata to actors."""
    body = clean_input(cfg)
    queries = cfg.get("_searchQueries")
    if queries is None:
        yield body
        return
    if not isinstance(queries, list) or not queries or any(
            not isinstance(q, str) or not q.strip() for q in queries):
        raise ValueError("_searchQueries must be a nonempty list of query strings")
    for query in dict.fromkeys(queries):
        yield {**body, "keyword": query}


def actor_id(key: str, cfg: dict) -> str:
    return (cfg.get("_actor") or ACTOR_FOR[key]).replace("/", "~")


def run_actor(key: str, run_input: dict, actor: str, max_wait_s: int = 1800) -> list:
    print(f"[{key}] starting {actor}", file=sys.stderr)
    run = _req("POST", f"/acts/{actor}/runs", body=run_input)["data"]
    run_id, t0 = run["id"], time.time()
    while run["status"] in ("READY", "RUNNING"):
        if time.time() - t0 > max_wait_s:
            sys.exit(f"[{key}] run {run_id} still {run['status']} after {max_wait_s}s")
        run = _req("GET", f"/actor-runs/{run_id}", query={"waitForFinish": 60},
                   timeout=90)["data"]
    if run["status"] != "SUCCEEDED":
        sys.exit(f"[{key}] run {run_id} ended {run['status']} - see "
                 f"https://console.apify.com/actors/runs/{run_id}")
    items = fetch_dataset(run["defaultDatasetId"])
    print(f"[{key}] {len(items)} items (dataset {run['defaultDatasetId']})", file=sys.stderr)
    return items


def fetch_dataset(dataset_id: str) -> list:
    out, offset, page = [], 0, 1000
    while True:
        chunk = _req("GET", f"/datasets/{dataset_id}/items",
                     query={"format": "json", "clean": "true",
                            "offset": offset, "limit": page})
        out.extend(chunk)
        if len(chunk) < page:
            return out
        offset += page


def _dump(obj, path: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(obj, fh, indent=1, ensure_ascii=False)
    print(f"wrote {path}", file=sys.stderr)


def cmd_scrape(a) -> int:
    inp = load_inputs()
    only = set(a.only.split(",")) if a.only else {"linkedin", "naukri", "indeed"}
    if "linkedin" in only:
        c = inp["linkedin"]
        _dump(run_actor("linkedin", clean_input(c), actor_id("linkedin", c)),
              os.path.join(a.outdir, "linkedin.json"))
    if "naukri" in only:
        c = inp["naukri_pass1"]
        _dump(run_actor("naukri_pass1", clean_input(c), actor_id("naukri_pass1", c)),
              os.path.join(a.outdir, "naukri.json"))
    if "indeed" in only:
        merged, seen = [], set()
        for key in ("indeed", "indeed_remote_pass"):
            c = inp[key]
            for body in search_inputs(c):
                for it in run_actor(key, body, actor_id(key, c)):
                    k = (it.get("id") or it.get("jobkey") or
                         json.dumps(it.get("urls") or it, sort_keys=True))
                    if k in seen:
                        continue
                    seen.add(k)
                    merged.append(it)
        _dump(merged, os.path.join(a.outdir, "indeed.json"))
    return 0


def cmd_details(a) -> int:
    with open(a.triage) as fh:
        tri = json.load(fh)
    prim = [j for j in tri["jobs"] if j.get("triage_priority") == "primary"]
    details, need_naukri = {}, []
    for j in prim:
        d = (j.get("description") or "").strip()
        if d:
            details[str(j["job_id"])] = d
        elif j["source"] == "naukri":
            need_naukri.append(str(j["job_id"]))
        else:
            print(f"no description in pass 1: {j['source']} {j['job_id']} "
                  f"{j['title']} @ {j['company']}", file=sys.stderr)
    if need_naukri and not a.no_naukri_pass2:
        tmpl = load_inputs()["naukri_pass2_template"]
        body = clean_input(tmpl)
        body["jobIds"] = need_naukri
        for it in run_actor("naukri_pass2", body, actor_id("naukri_pass2_template", tmpl)):
            jid, d = str(it.get("jobId") or it.get("id") or ""), it.get("description")
            if jid and d:
                details[jid] = d
    missing = [str(j["job_id"]) for j in prim if str(j["job_id"]) not in details]
    print(f"primaries={len(prim)} with_description={len(details)} "
          f"naukri_pass2={len(need_naukri)} still_missing={len(missing)}", file=sys.stderr)
    _dump(details, a.out)
    return 0


def cmd_dataset(a) -> int:
    _dump(fetch_dataset(a.dataset_id), a.out)
    return 0


def self_test(a=None) -> int:
    """Offline checks: expansion, metadata stripping, legacy inputs and merging."""
    from types import SimpleNamespace
    from unittest.mock import patch

    cfg = {"keyword": "old", "location": "Remote", "_actor": "test",
           "_searchQueries": ["first", "second", "first"]}
    bodies = list(search_inputs(cfg))
    assert [b["keyword"] for b in bodies] == ["first", "second"]
    assert all(b == {"keyword": q, "location": "Remote"}
               for b, q in zip(bodies, ["first", "second"]))
    assert list(search_inputs({"keyword": "old"})) == [{"keyword": "old"}]
    for invalid in ([], "query", [""]):
        try:
            list(search_inputs({"_searchQueries": invalid}))
        except ValueError:
            pass
        else:
            raise AssertionError("invalid query configuration accepted")
    inputs = {"indeed": cfg, "indeed_remote_pass": {**cfg, "location": "Bengaluru"}}
    module = sys.modules[__name__]
    with patch.object(module, "load_inputs", return_value=inputs), \
         patch.object(module, "run_actor", return_value=[{"id": "shared"},
                           {"title": "A"}, {"title": "B"}]) as run, \
         patch.object(module, "_dump") as dump:
        assert cmd_scrape(SimpleNamespace(only="indeed", outdir="unused")) == 0
        assert run.call_count == 4
        assert len(dump.call_args.args[0]) == 3
    print("apify_fetch self-test: passed (offline)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("self-test")
    sub.add_parser("whoami")
    s = sub.add_parser("scrape")
    s.add_argument("--outdir", required=True)
    s.add_argument("--only", help="comma list of linkedin,naukri,indeed (default all)")
    d = sub.add_parser("details")
    d.add_argument("--triage", required=True)
    d.add_argument("--out", required=True)
    d.add_argument("--no-naukri-pass2", action="store_true")
    g = sub.add_parser("dataset")
    g.add_argument("dataset_id")
    g.add_argument("--out", required=True)
    ap.add_argument("--profile", help="profile name or path (default: JOBSEARCH_PROFILE)")
    a = ap.parse_args()
    jsprofile.select(a.profile)
    return {"scrape": cmd_scrape, "details": cmd_details, "dataset": cmd_dataset, "self-test": self_test, "whoami": cmd_whoami}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
